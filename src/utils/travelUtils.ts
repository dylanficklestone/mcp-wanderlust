import { DestinationItem, SearchPreferences, SupportedCurrency } from '../types/travel.ts';

export const CURRENCY_RATES: Record<SupportedCurrency, { symbol: string; rate: number; name: string }> = {
  USD: { symbol: '$', rate: 1.0, name: 'US Dollar' },
  EUR: { symbol: '€', rate: 0.92, name: 'Euro' },
  GBP: { symbol: '£', rate: 0.79, name: 'British Pound' },
  JPY: { symbol: '¥', rate: 154.0, name: 'Japanese Yen' },
  AUD: { symbol: 'A$', rate: 1.52, name: 'Australian Dollar' },
  CAD: { symbol: 'C$', rate: 1.38, name: 'Canadian Dollar' },
};

export function formatCurrency(amountUsd: number, currency: SupportedCurrency = 'USD'): string {
  const info = CURRENCY_RATES[currency] || CURRENCY_RATES.USD;
  const converted = amountUsd * info.rate;
  if (currency === 'JPY') {
    return `${info.symbol}${Math.round(converted).toLocaleString()}`;
  }
  return `${info.symbol}${Math.round(converted).toLocaleString()}`;
}

export function exportDestinationToMarkdown(dest: DestinationItem, prefs?: SearchPreferences): string {
  const dateStr = new Date(dest.generatedAt).toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  });

  const tripDays = prefs?.customTripDays || (prefs?.tripLength === 'weekend' ? 3 : prefs?.tripLength === 'extended' ? 14 : 7);
  const totalJourneySpend = dest.budget.dailyTotalUsd * tripDays;

  return `# ${dest.name}, ${dest.country} — Tailored Travel Guide
*Generated by Wanderlust AI on ${dateStr}*

> **"${dest.hook}"**

---

## 🎯 Why This Fits Your Journey
${dest.relevanceRationale.map((r) => `- ${r}`).join('\n')}

---

## ✈️ Logistics & Access
- **Primary Airport:** ${dest.logistics.primaryAirportName} (${dest.logistics.primaryAirportCode})
- **Flight Duration from Origin:** ${dest.logistics.flightDurationEstimate} (${dest.logistics.directFlightAvailable ? 'Direct Available' : dest.logistics.transitHubs || '1 Stop'})
- **Estimated Distance:** ${dest.logistics.estimatedDistanceKm || 'N/A'} km
- **Estimated Carbon Footprint:** ${dest.logistics.carbonFootprintKg || 'N/A'} kg CO2e
- **Visa & Entry Rules:** ${dest.logistics.visaSnapshot}
- **Top Recommended Quarter:** ${dest.logistics.bestNeighborhood}

---

## 💰 Estimated Budget (per person)
- **Lodging / Hotel:** $${dest.budget.dailyStayUsd} / day
- **Food & Dining:** $${dest.budget.dailyFoodUsd} / day
- **Local Transit:** $${dest.budget.dailyTransportUsd} / day
- **Daily Estimated Spend:** **$${dest.budget.dailyTotalUsd} / day** (${dest.budget.localCurrencyCode})
- **Customized Journey Length:** **${tripDays} Days**
- **Projected Total Journey Spend:** **$${totalJourneySpend}** (${dest.budget.localCurrencyCode})

---

## 📅 Curated 3-Day Highlight Itinerary

${dest.curatedItinerary
  .map(
    (day) => `### Day ${day.day}: ${day.title}
- **Morning:** ${day.morning}
- **Afternoon:** ${day.afternoon}
- **Evening:** ${day.evening}
`
  )
  .join('\n')}

---

## 🏨 Curated Stays & Hotel Recommendations
${
  dest.hotelRecommendations && dest.hotelRecommendations.length > 0
    ? dest.hotelRecommendations
        .map(
          (h) => `### ${h.name} (${h.tier}) — ★ ${h.rating}/5.0
- **Nightly Rate:** ~$${h.pricePerNightUsd} USD / night
- **Location:** ${h.neighborhood}
- **Vibe:** ${h.vibe}
- **Key Amenities:** ${h.amenities.join(', ')}
- **Booking Note:** *${h.bookingNote}*
`
        )
        .join('\n')
    : '_Hotel recommendations available in destination dossier._'
}

---

## 💡 Insider Pro-Tip
> ${dest.proTip}

---

## 🗺️ Local Context & Seasonal Highlights
${dest.liveContextHighlights?.map((h) => `- ${h}`).join('\n') || '- Check seasonal calendar before departure.'}
- **Seasonal Highlight:** ${dest.localFestivalOrEvent || 'Open-air seasonal markets and twilight walks'}
- **Coordinates:** [${dest.geoCoordinates.lat}, ${dest.geoCoordinates.lng}]
- **Google Maps:** ${dest.geoCoordinates.mapsUrl}

---
*Crafted dynamically with Wanderlust AI via Gemini 3.1 Flash and Model Context Protocol (MCP).*
`;
}

export function downloadMarkdownFile(filename: string, content: string) {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

